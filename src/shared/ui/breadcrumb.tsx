import { mergeProps } from "@base-ui/react/merge-props";
import { useRender } from "@base-ui/react/use-render";
import { cn } from "cn";
import { ChevronRightIcon, MoreHorizontalIcon } from "lucide-react";
import type * as React from "react";

type BreadcrumbProps = React.ComponentProps<"nav">;

export const Breadcrumb = ({ className, ...props }: BreadcrumbProps) => {
  return (
    <nav aria-label="breadcrumb" data-slot="breadcrumb" className={cn(className)} {...props} />
  );
};

type BreadcrumbListProps = React.ComponentProps<"ol">;

export const BreadcrumbList = ({ className, ...props }: BreadcrumbListProps) => {
  return (
    <ol
      data-slot="breadcrumb-list"
      className={cn(
        "wrap-break-word flex flex-wrap items-center gap-1.5 text-muted-foreground text-sm sm:gap-2.5",
        className,
      )}
      {...props}
    />
  );
};

type BreadcrumbItemProps = React.ComponentProps<"li">;

export const BreadcrumbItem = ({ className, ...props }: BreadcrumbItemProps) => {
  return (
    <li
      data-slot="breadcrumb-item"
      className={cn("inline-flex items-center gap-1.5", className)}
      {...props}
    />
  );
};

type BreadcrumbLinkProps = useRender.ComponentProps<"a">;

export const BreadcrumbLink = ({ className, render, ...props }: BreadcrumbLinkProps) => {
  return useRender({
    defaultTagName: "a",
    props: mergeProps<"a">(
      {
        className: cn("transition-colors hover:text-foreground", className),
      },
      props,
    ),
    render,
    state: {
      slot: "breadcrumb-link",
    },
  });
};

type BreadcrumbPageProps = React.ComponentProps<"span">;

export const BreadcrumbPage = ({ className, ...props }: BreadcrumbPageProps) => {
  return (
    // biome-ignore lint/a11y/useFocusableInteractive: generated by shadcn/ui
    // biome-ignore lint/a11y/useSemanticElements: generated by shadcn/ui
    <span
      data-slot="breadcrumb-page"
      role="link"
      aria-disabled="true"
      aria-current="page"
      className={cn("font-normal text-foreground", className)}
      {...props}
    />
  );
};

type BreadcrumbSeparatorProps = React.ComponentProps<"li">;

export const BreadcrumbSeparator = ({
  children,
  className,
  ...props
}: BreadcrumbSeparatorProps) => {
  return (
    <li
      data-slot="breadcrumb-separator"
      role="presentation"
      aria-hidden="true"
      className={cn("[&>svg]:size-3.5", className)}
      {...props}
    >
      {children ?? <ChevronRightIcon />}
    </li>
  );
};

type BreadcrumbEllipsisProps = React.ComponentProps<"span">;

export const BreadcrumbEllipsis = ({ className, ...props }: BreadcrumbEllipsisProps) => {
  return (
    <span
      data-slot="breadcrumb-ellipsis"
      role="presentation"
      aria-hidden="true"
      className={cn("flex size-5 items-center justify-center [&>svg]:size-4", className)}
      {...props}
    >
      <MoreHorizontalIcon />
      <span className="sr-only">More</span>
    </span>
  );
};
