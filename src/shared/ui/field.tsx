type FieldMessageProps = React.ComponentProps<"div"> & {
  errors?: FieldErrorProps["errors"];
  description?: React.ReactNode;
};

/**
 * Always keeps one line below the input: shows the error if there is one, otherwise the
 * description, otherwise an empty line. Fields in a row then never shift when an error appears.
 */
export const FieldMessage = ({ className, errors, description, ...props }: FieldMessageProps) => {
  const hasError = errors?.some((error) => error?.message);

  return (
    <div data-slot="field-message" className={cn("min-h-5", className)} {...props}>
      {hasError ? (
        <FieldError errors={errors} className="leading-5" />
      ) : (
        description && <FieldDescription className="leading-5">{description}</FieldDescription>
      )}
    </div>
  );
};
